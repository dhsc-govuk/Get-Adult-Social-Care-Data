export function isAcceptableEmail(email: unknown): boolean {
  if (typeof email === 'string') {
    const domain = email.split('@')[1];
    return ACCEPTABLE_EMAIL_DOMAINS.includes(domain);
  }
  return false;
}

export function isBadQueryStringValue(id: unknown): boolean {
  const EXPECTED_ID_VALUES = ['u:ni', 'u:rm', 'u:la', 'u:x'];

  return (
    typeof id === 'string' &&
    (EXPECTED_ID_VALUES.includes(id) === false || id !== 'u:la')
  );
}
